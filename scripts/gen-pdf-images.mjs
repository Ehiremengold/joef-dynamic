/**
 * Regenerate the images embedded in the PDFs:
 *   lib/pdf/logo-base64.ts       from public/images/logo.png
 *   lib/pdf/signature-base64.ts  from public/images/principal-signature.png (optional)
 * Run this whenever either image changes:
 *   node scripts/gen-pdf-images.mjs
 *
 * The images are embedded as base64 strings directly in the JS bundle (rather
 * than read from disk at request time) so PDF generation never depends on
 * public/ being present in the serverless function's filesystem at runtime.
 * The signature should be a PNG of the principal's signature, ideally on a
 * transparent or white background and cropped close.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const header = "// Auto-generated by scripts/gen-pdf-images.mjs — do not edit by hand.\n";

const png = readFileSync(new URL("../public/images/logo.png", import.meta.url));
const base64 = png.toString("base64");
writeFileSync(
  new URL("../lib/pdf/logo-base64.ts", import.meta.url),
  `${header}export const LOGO_PNG_BASE64 = ${JSON.stringify(base64)};\n`
);
console.log(`Wrote lib/pdf/logo-base64.ts (${(base64.length / 1024).toFixed(0)} KB base64)`);

const signaturePath = new URL("../public/images/principal-signature.png", import.meta.url);
const signature = existsSync(signaturePath) ? readFileSync(signaturePath).toString("base64") : null;
writeFileSync(
  new URL("../lib/pdf/signature-base64.ts", import.meta.url),
  `${header}// Null until public/images/principal-signature.png exists and the script is run.\n` +
    `export const SIGNATURE_PNG_BASE64: string | null = ${JSON.stringify(signature)};\n`
);
console.log(signature ? "Wrote lib/pdf/signature-base64.ts" : "No principal-signature.png — signature left out of report sheets");
